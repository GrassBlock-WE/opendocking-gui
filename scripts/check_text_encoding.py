#: `{image: source}` -- what cp936 reads a character's own UTF-8 bytes as, when
#: that reading **loses nothing**.
#:
#: Derived from the byte ranges rather than typed as a table, for two reasons.
#: A two-byte UTF-8 sequence (lead `0xC2`-`0xDF`, trail `0x80`-`0xBF`) is the
#: only shape that can be read as a *single* cp936 character, so those 1,920
#: sequences are the entire reachable set and every one of them decodes. And a
#: 1,920-character table of the damage written out literally would put the
#: damage into the file that hunts it -- the same self-reference trap this file
#: records for its own `U+FFFD` constant.
#:
#: `U+00C5` is `C3 85`. Read as cp936 that pair is `U+811C`, and that is the
#: whole of the third mojibake flavour: the file decodes as valid UTF-8, no byte
#: was lost, and no `?` or `U+FFFD` was written. Nothing about the result is
#: malformed, which is exactly why no byte-level predicate found it.
def _gbk_lossless_pairs() -> dict[str, str]:
    out: dict[str, str] = {}
    for lead in range(0xC2, 0xE0):
        for trail in range(0x80, 0xC0):
            raw = bytes((lead, trail))
            try:
                out[raw.decode("gbk")] = raw.decode("utf-8")
            except UnicodeDecodeError:
                pass
    return out


GBK_LOSSLESS = _gbk_lossless_pairs()


def _one_gbk(pair: bytes):
    """The single cp936 character `pair` decodes to, or `None`."""
    try:
        s = pair.decode("gbk")
    except UnicodeDecodeError:
        return None
    return s if len(s) == 1 else None


def _reachable(lead: int, trail: int, width: int) -> bool:
    """Can a valid UTF-8 sequence of this width start with these two bytes?

    The overlong and surrogate rules live in the decoder, not here, so this asks
    by trying rather than by arithmetic. It is what keeps the map below honest
    about which byte pairs have a source at all: `(0xE0, 0x80)` cannot begin a
    three-byte sequence, and an image with no possible source is not a signature.

    **The `width == 2` branch was missing, and the cp936 maps never noticed.**
    This function was written for the two multi-byte widths only, and for those
    a third byte always follows -- so it appended one unconditionally and asked
    whether a *three*-byte sequence existed. The cp1252 derivation below is the
    first caller to pass `width == 2`, where appending a third byte turns a
    perfectly good two-byte sequence into an invalid one: every pair failed,
    `CP1252_COMPLETE` came out empty, and the predicate's entire complete-
    substitution arm was dead while the run still reported a green. A helper
    that is wrong only for a caller who does not exist yet is the quietest kind
    of wrong there is, and the only reason this was caught is that the fixture
    the new rule depends on refused to fire.
    """
    if width == 2:
        try:
            bytes((lead, trail)).decode("utf-8")
            return True
        except UnicodeDecodeError:
            return False
    for c in range(0x80, 0xC0):
        if width == 4:
            for d in range(0x80, 0xC0):
                try:
                    bytes((lead, trail, c, d)).decode("utf-8")
                    return True
                except UnicodeDecodeError:
                    continue
        else:
            try:
                bytes((lead, trail, c)).decode("utf-8")
                return True
            except UnicodeDecodeError:
                continue
    return False


def _gbk_multibyte_first() -> dict[str, set[tuple[int, int]]]:
    """`{image: {(lead, trail)}}` for the **first** image of a 3- or 4-byte sequence.

    The same derivation as `GBK_LOSSLESS` and for the same reason: computed from
    the byte ranges, never typed. Measured size is 960 three-byte and 256
    four-byte image characters, against `GBK_LOSSLESS`'s 1,920.

    **Why the map stops at the first image character.** A UTF-8 sequence longer
    than two bytes cannot survive a cp936 read. cp936 takes two bytes per
    character for every lead byte in `0x81`-`0xFE`, so `E4 BD A0` is read as
    one character from `(E4, BD)` and then the trailing `A0` is joined to the
    first byte of whatever followed -- which is why the damage walks its
    neighbour. Only the *first* image is a function of the damaged character's
    own bytes; the second belongs to the neighbour and says nothing about where
    the source was. Keying on both would have produced a much larger map and a
    worse one.

    **Why the value is a byte pair and not the source character.** A four-byte
    sequence has up to 4,096 sources, and materialising those for every image
    would be over a million strings at import for a map that is consulted only
    for the handful of characters a file actually contains. `_multibyte_sources`
    regenerates them on demand instead.
    """
    out: dict[str, set[tuple[int, int]]] = {}
    for width, leads in ((3, range(0xE0, 0xF0)), (4, range(0xF0, 0xF5))):
        for lead in leads:
            for trail in range(0x80, 0xC0):
                img = _one_gbk(bytes((lead, trail)))
                if img and _reachable(lead, trail, width):
                    out.setdefault(img, set()).add((lead, trail))
    return out


GBK_MULTIBYTE = _gbk_multibyte_first()


def _multibyte_sources(pairs) -> set[str]:
    """Every valid character whose UTF-8 encoding begins with one of `pairs`."""
    out: set[str] = set()
    for lead, trail in pairs:
        for c in range(0x80, 0xC0):
            try:
                out.add(bytes((lead, trail, c)).decode("utf-8"))
            except UnicodeDecodeError:
                pass
            for d in range(0x80, 0xC0):
                try:
                    out.add(bytes((lead, trail, c, d)).decode("utf-8"))
                except UnicodeDecodeError:
                    pass
    return out


# --------------------------------------------------------------------------
# The cp1252 class: a SINGLE-BYTE codec, and the modal accident on earth
# --------------------------------------------------------------------------

#: `(width, lead bytes)` for every multi-byte UTF-8 sequence, exactly as the
#: cp936 derivations above enumerate theirs. A two-byte UTF-8 sequence is the
#: only shape a single-byte codec can read as *two* characters, and a three-
#: or four-byte one is read as that many, so the first two characters of an
#: image are a function of the first two bytes and nothing else.
CP1252_LEAD_WIDTHS = ((2, range(0xC2, 0xE0)),
                      (3, range(0xE0, 0xF0)),
                      (4, range(0xF0, 0xF5)))

#: The trail bytes a lead byte can be followed by. Tried rather than computed
#: in `_reachable`, because the overlong and surrogate rules live in the
#: decoder, not in arithmetic.
CP1252_TRAILS = range(0x80, 0xC0)


def _one_cp1252(raw: bytes):
    """The single cp1252 character `raw` decodes to, or `None`.

    Five of the 64 bytes in `0x80`-`0x9F` are undefined in cp1252, so this
    returns `None` for them. That is not an edge case to be smoothed over --
    `_cp1252_class` says where those sources go instead.
    """
    try:
        s = raw.decode("cp1252")
    except UnicodeDecodeError:
        return None
    return s if len(s) == 1 else None


def _cp1252_class() -> tuple[dict[str, str], dict[str, tuple[int, int]],
                             frozenset[str]]:
    """`(complete, prefix, second)` -- the reachable cp1252 image class.

    **Computed from the codec's own table, never typed, and for the same
    reason `GBK_LOSSLESS` is.** A typed list of the reachable images would put
    the mojibake into the file that hunts mojibake, which is the trap this file
    records twice already. The codec is the table; nothing here is transcribed.

    **The return value has two halves, and the split is the whole finding.** A
    2-byte UTF-8 source becomes exactly two cp1252 characters, so the pair *is*
    the whole damage and nothing follows it to corroborate or contradict it. A
    3- or 4-byte source becomes three or four characters, of which the first
    two are the pair and the third is always another character out of the same
    `0x80`-`0xBF` band -- so for those the pair is a **prefix**, and the band
    character after it is a fact about the codec rather than about the prose.
    The lead byte says which case a pair is in, with no overlap and no
    judgement, and that is what lets the predicate below run one arm outright
    and ask the other for corroboration.

    Measured size: 1,770 complete images and 1,121 prefix images, over 59
    distinct second characters. The two counts cannot overlap, because a lead
    byte in `0xC2`-`0xDF` can only begin a 2-byte sequence and one in `0xE0`-
    `0xF4` can only begin a 3- or 4-byte one. `complete` maps an image to the
    one character it can only have come from; `prefix` maps it to the byte pair
    its sources start with, because a prefix has thousands.

    **What is absent here is not a gap in the class.** A source character whose
    own bytes cp1252 cannot decode does not produce a different mojibake: it
    makes the *whole read* fail, and PowerShell then writes `U+FFFD` or `?` in
    its place, which `pred_replacement` and `pred_lost_byte` already hold. So
    the set below is complete for the part of the class that reaches a file as
    readable text, and the rest of the class is owned by two other checks
    rather than by a third shape nobody derived.
    """
    complete: dict[str, str] = {}
    prefix: dict[str, tuple[int, int]] = {}
    second: set[str] = set()
    for width, leads in CP1252_LEAD_WIDTHS:
        for lead in leads:
            c1 = _one_cp1252(bytes((lead,)))
            if c1 is None:
                continue
            for trail in CP1252_TRAILS:
                c2 = _one_cp1252(bytes((trail,)))
                if c2 is None:
                    continue
                if not _reachable(lead, trail, width):
                    continue
                second.add(c2)
                if width == 2:
                    complete.setdefault(c1 + c2,
                                        bytes((lead, trail)).decode("utf-8"))
                else:
                    prefix.setdefault(c1 + c2, (lead, trail))
    return complete, prefix, frozenset(second)


CP1252_COMPLETE, CP1252_PREFIX, CP1252_SECOND = _cp1252_class()

