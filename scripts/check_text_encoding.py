#: The two-character prefix of the image of `ch`, or `None` when `ch`'s own
#: bytes do not survive a cp1252 read. The fixture builder and the self-test
#: build their cases through this and through the tables above, so a specimen
#: is derived from the same codec the predicate reads rather than transcribed
#: from a second list that could drift.
def cp1252_image_of(ch: str) -> str | None:
    raw = ch.encode("utf-8")
    if len(raw) < 2:
        return None
    try:
        return raw.decode("cp1252")[:2]
    except UnicodeDecodeError:
        return None

