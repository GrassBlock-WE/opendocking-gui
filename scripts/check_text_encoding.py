def looks_binary(data: bytes) -> bool:
    """A NUL in the first 8 KiB. Crude, stated, and the right question here.

    A compiled object and a zip both trip it, and no text file this repository
    has does. Deciding it by extension instead would mean a new binary type is
    scanned as text until somebody remembers, which is the same oversight this
    gate is about, one level down.
    """
    return b"\x00" in data[:8192]


def label_of(path: Path) -> str:
    return path.suffix.lower() if path.suffix else NO_SUFFIX


def iter_files(root: Path):
    """Every file under `root`, with `SKIP_DIRS` pruned **at descent time**.

    `Path.rglob("*")` filters nothing: it walks the whole tree and the caller
    discards what it does not want afterwards, so a skipped directory is entered
    before it is recognised. That is not only slow, it is a crash. This gate was
    measured going red with `DID NOT FINISH` -- `FileNotFoundError` on
    `target/release/deps/.tmpXXXX.temp-archive` -- because a cargo build was
    running on the same machine and its temporary archive directory disappeared
    between the directory listing and the read. The old version of this file
    walked the tree the same way and had the same exposure; it just had never
    been run while a build was in flight.

    So the walk is hand-rolled, prunes by name before descending, and treats a
    directory that vanishes under it as absent rather than fatal. Files that
    vanish are reported as unreadable by `walk`, which is a different answer from
    "clean" and from "damaged".
    """
    stack = [root]
    while stack:
        here = stack.pop()
        try:
            with os.scandir(here) as it:
                entries = sorted(it, key=lambda e: e.name)
        except OSError:
            # Gone, or not readable. Either way there is nothing here to judge,
            # and a directory that cannot be opened is not evidence of damage.
            continue
        for entry in entries:
            if entry.is_dir(follow_symlinks=False):
                if entry.name not in SKIP_DIRS:
                    stack.append(Path(entry.path))
            else:
                yield Path(entry.path)


def walk(root: Path) -> tuple[list[Path], list[tuple[Path, str]]]:
    """`(in-scope, unreadable)` under `root`.

    A file that cannot be read is returned in the second list with the reason,
    and never silently dropped: an unreadable file is an `OSError`, which is a
    different answer from "damaged" and a different answer again from "absent".
    """
    in_scope: list[Path] = []
    unreadable: list[tuple[Path, str]] = []
    for path in iter_files(root):
        rel = path.relative_to(root)
        label = label_of(path)
        if label != NO_SUFFIX and label not in COVERED_TYPES:
            continue
        try:
            data = path.read_bytes()
        except OSError as exc:
            unreadable.append((rel, f"{type(exc).__name__}: {exc}"))
            continue
        if looks_binary(data):
            # An extensionless file that is really a binary. Not in scope, and
            # not an error: `$null` is 668 B of text and this is the test that
            # tells the two apart without naming either.
            continue
        in_scope.append(rel)
    return in_scope, unreadable


def encode_rel(rel: Path, root: Path) -> str:
    """The key an exemption is filed under.

    Repo-relative when the file is in the tree, absolute when it is not, so the
    self-test can exempt its own Latin-1 file without this gate knowing where
    `%TEMP%` is.
    """
    try:
        return rel.relative_to(root).as_posix()
    except ValueError:
        return rel.as_posix()


def verdicts(data: bytes) -> dict[str, str]:
    """Every predicate's reason for these bytes, keyed by predicate name."""
    out = {}
    for _label, pred, _short in PREDICATES:
        reason = pred(data)
        if reason:
            out[pred.__name__] = reason
    return out


def first_reason(reasons: dict[str, str]) -> str:
    return reasons[next(iter(reasons))]


def describe(path: Path) -> str:
    return "%s, %d B" % (path.as_posix(), path.stat().st_size)


