def _adjacent_gbk_images(text: str, table=GBK_LOSSLESS) -> bool:
    """Two characters from `table` side by side.

    A volume test rather than a dictionary, and the docstring at the predicate
    says so: the reachable set is about 9% of the ideographs, so a short file
    does not produce a pair by chance and a long document cannot avoid one.

    A linear scan rather than a 1,920-character regex class, because a class
    that long is a thing nobody can read and therefore a thing nobody reviews.

    The table is a parameter so the multi-byte map gets the same test rather
    than a re-implementation of it. Its reachable set is *smaller* -- 960 of the
    same ideograph range rather than 1,920 -- so the volume argument is if
    anything stronger, and it was measured rather than assumed: over the 63
    in-scope files that carry CJK, exactly one of the 960 occurs at all.
    """
    prev = False
    for ch in text:
        cur = ch in table
        if cur and prev:
            return True
        prev = cur
    return False


def pred_mojibake_cp1252(data: bytes) -> str | None:
    """A character in this file re-read as cp1252 and written back.

    **This is the blind spot the two predicates above it do not cover, and
    the reason it was worth a codec rather than a list.** The previous two
    rules name two specific two-character sequences. A measurement over the
    reachable set found **2,891** of them, the most common being the image of
    `U+00E9` -- the modal mojibake on earth, and the shape any Western
    PowerShell 5.1 `Get-Content -Raw` / `Set-Content -Encoding UTF8` pair
    produces from an accented letter. Two named pairs out of 2,891 is a gate
    that is blind to the common case and precise about an uncommon one, which
    is the worst of both.

    **Three arms, and which one runs is decided by the lead byte, not by a
    judgement about the text.**

    * *prefix* -- a 3- or 4-byte source. The pair is the first two characters
      of a three-or-four-character image, and the third character is always
      another member of the same band, because that is what the codec does to
      the third byte. So this arm requires that third character, and a correct
      file does not contain an accented letter followed by two band
      characters. Reported outright.
    * *complete, second character not in `CP1252_RISKY_SECOND`* -- a 2-byte
      source, and the pair is the entire damage. 50 of the 59 second
      characters are not things that follow an accented letter in correct
      text, so for those the pair is a verdict on its own. Reported outright.
    * *complete, second character in `CP1252_RISKY_SECOND`* -- reported only
      when this same file already produced one of the two findings above,
      which is the corroboration the cp936 arm gets from the file also
      spelling the source character. The corroborating finding is named in
      the message, so the reader can see what vouched for the pair rather
      than being asked to take it.

    **The arm that can be wrong, and is not claimed to be otherwise, is the
    corroboration one.** This repository writes angstrom-cubed 52 times over, as
    measured on 2026-10-03, and
    that is indistinguishable, byte for byte, from a damaged `U+00F3`; the
    only thing separating them is whether anything else in the file is also
    damaged. A file whose *only* accented damage produces one of the six
    listed second characters is therefore not caught. That sentence is the
    honest description of this rule, and `CP1252_RISKY_SECOND` names the six
    rather than hiding the gap. Uncaught here is not the same as unknown: the
    self-test builds one of these files on purpose and asserts it is the one
    case that stays green.
    """
    text = _text(data)
    if text is None:
        return None
    direct: list[tuple[str, str, int]] = []
    risky: list[tuple[str, str, int]] = []
    for i in range(len(text) - 1):
        pair = text[i:i + 2]
        if pair in CP1252_PREFIX:
            # A 3- or 4-byte source always yields a third character out of the
            # same band, so requiring it costs no coverage and removes the
            # entire class of "an accented letter followed by one band
            # character" that a complete image shares.
            nxt = text[i + 2] if i + 2 < len(text) else ""
            if nxt in CP1252_SECOND:
                direct.append((pair, "prefix of a 3- or 4-byte character", i))
        elif pair in CP1252_COMPLETE:
            if pair[1] in CP1252_RISKY_SECOND:
                risky.append((pair, CP1252_RISKY_SECOND[pair[1]], i))
            else:
                direct.append((pair, "the whole image of one character", i))
    if not direct:
        return None
    pair, arm, at = direct[0]
    src = CP1252_COMPLETE.get(pair)
    lead, trail = CP1252_PREFIX.get(pair, (0, 0))
    as_hex = "U+%04X U+%04X" % (ord(pair[0]), ord(pair[1]))
    if src is not None:
        origin = ("the image of U+%04X re-read as cp1252" % ord(src))
    else:
        origin = ("the first two characters of a 3- or 4-byte character's "
                  "image, from UTF-8 lead byte %02X and trail %02X"
                  % (lead, trail))
    n_more = len(direct) - 1
    tail = ("" if not n_more else
            f" and {n_more} more uncorroborated pair(s) in this file")
    vouched = ""
    if risky:
        first_pair, why, _at = risky[0]
        vouched = (f". {len(risky)} further pair(s) here would have needed "
                   f"corroboration and got it from the finding above: "
                   f"U+%04X U+%04X, which is also what a correct file can "
                   f"contain ({why})"
                   % (ord(first_pair[0]), ord(first_pair[1])))
    return (f"carries {as_hex} at offset {at}: {origin}, {arm}. A Western "
            f"PowerShell 5.1 `Get-Content -Raw` / `Set-Content -Encoding "
            f"UTF8` pair does this to every accented and typographic "
            f"character in a file, and it is the most common encoding damage "
            f"there is{tail}{vouched}"
            + _not_damage())


def pred_lossless_gbk(data: bytes) -> str | None:
    """A cp936 image of a character this same file also writes correctly.

    **What it hunts.** The one flavour of a Windows round trip that leaves no
    trace of damage at all. `U+00C5` is `C3 85`; a Chinese-Windows
    `Get-Content -Raw` reads that pair as cp936 and gets `U+811C`, and
    `Set-Content -Encoding UTF8` writes the result back as valid UTF-8. The
    file decodes cleanly, no byte was lost, so `pred_lost_byte` cannot fire --
    it needs a trailing `?` -- and `pred_mojibake_angstrom` cannot fire either,
    because it knows the *cp1252* image of `U+00C5` (`U+00C3 U+2026`) and this
    is the cp936 one. This gate reported 20/20 on a tree carrying three of
    these in a Rust source file. That is the whole reason it exists.

    **Two conditions, both measured rather than argued.** This tree holds 105,006
    CJK ideographs across 16 in-scope files (measured 2026-10-02; an earlier
    reading the same day said 105,010 across 18, and the difference is other
    agents' files rather than a change to this rule), written deliberately, so
    "contains a CJK ideograph" is a rule that fires on everything and means
    nothing. The two arms below are what make it discriminate:

    * *the file is not writing Chinese.* Two of the 1,920 side by side. The
      reachable set is **sparse** -- 1,920 of the roughly 20,992 ideographs in
      `U+4E00`-`U+9FFF`, about 9% -- so this arm is a volume test and not a
      dictionary: a file carrying a handful of ideographs will not happen to
      contain an adjacent pair of them, and a document carrying tens of
      thousands of them cannot avoid one. The largest ideograph-bearing file in
      this tree carries over 70,000 and that figure moves every time somebody
      edits the document, which is exactly why the argument is stated as a
      property of the range rather than as a number: a quoted count here is a
      count that is wrong within a day, and a wrong count is what a reader
      checks a gate against. Measured over this tree it rules out **13 of the
      16** in-scope files that carry ideographs, by itself, and the 13 has
      held across every reading taken while the denominator moved.
    * *the file writes the character that was replaced, correctly, elsewhere.*
      That is what makes it mojibake rather than a rare Chinese character: the
      same file already knows how to spell the sign, and here it is spelled
      wrong. It is what rules out the **three** the first arm does not:
      `README.en.md`, whose two ideographs (`U+4E2D`, `U+6587`) are both outside
      the reachable set; `scripts/prep_check.py`, whose Chinese is
      matched-output prose inside two regexes; and
      `scripts/check_repo_docs.py`, which writes a Unicode **range**
      (`U+4E00`-`U+9FFF`) and holds no Latin-1 character that either endpoint is
      the cp936 image of. Without this arm all three would be red, and
      `check_repo_docs.py` would be red on a shape that is not damage at all.

    **What it cannot catch, so a reader does not conclude too much:**

    * *A file damaged in one place and nowhere else correctly.* The second arm
      needs both halves in the same file. A source file whose only non-ASCII
      were a single substituted `U+00C5` would pass this.
    * *Damage outside the 1,920.* A three- or four-byte UTF-8 sequence read as
      cp936 takes the *next* byte as a second character's trail, so it garbles
      its neighbour too. That is the loud flavour; no predicate here is aimed
      at it, and this one certainly is not.
    * *Which character should be there.* The report says a character is wrong
      here and names it; it never asserts the repair. The inverse map is a
      fact about the codec, not a claim about the file's intent.
    * *A rare Chinese character that collides.* If a file legitimately contains
      both a Latin-1 character and the ideograph cp936 maps it onto, this fires
      on correct content. It is the one shape of false positive the rule has,
      which is why the message asks for a second reading rather than asserting
      a fix.
    """
    text = _text(data)
    if text is None:
        return None
    if _adjacent_gbk_images(text):
        return None
    present = set(text)
    hits = sorted((text.index(image), image, source)
                  for image, source in GBK_LOSSLESS.items()
                  if image in present and source in present)
    if not hits:
        return None
    off, image, source = hits[0]
    places = sum(text.count(i) for _o, i, _s in hits)
    more = ("" if len(hits) == 1 else
            f" The other {len(hits) - 1} character(s) with the same shape are "
            f"named in the full report for this file")
    return (f"carries {len(hits)} losslessly-substituted cp936 character(s) in "
            f"{places} place(s), first at line {text.count(chr(10), 0, off) + 1} "
            f"offset {off}: "
            f"U+{ord(image):04X} is what cp936 reads the UTF-8 bytes of "
            f"U+{ord(source):04X}, and this file writes both. The second one "
            f"therefore arrived by being misread rather than by being typed, "
            f"and nothing about the file is malformed: it decodes as UTF-8, it "
            f"carries no `?` and no U+FFFD, which is exactly why "
            f"`pred_lost_byte` and `pred_mojibake_angstrom` are both blind to "
            f"it.{more}"
            + _not_damage())


def pred_multibyte_gbk(data: bytes) -> str | None:
    """The cp936 image of a three- or four-byte character this file also spells.

    **The class this closes, and why it was described but unmeasured until
    now.** `pred_lossless_gbk` handles a UTF-8 sequence of exactly two bytes,
    because that is the only shape cp936 can read back as a *single* character.
    A three- or four-byte sequence cannot: cp936 takes two bytes per character
    for every lead byte in `0x81`-`0xFE`, so `E6 96 87` is read as one character
    from `(E6, 96)` and its trailing `87` is joined to the first byte of
    whatever came next. The damage therefore walks its neighbour, which is why
    the old docstring called this "the loud flavour" and pointed at no rule for
    it. **It is enumerated here, derived at import from the byte ranges exactly
    as `GBK_LOSSLESS` is** -- 960 three-byte and 256 four-byte image characters
    -- and it is enumerable because the image factorises: the first image
    depends only on the damaged character's own first two bytes, so the reachable
    set is a set of 1,024 and 320 byte pairs rather than 15.7 million
    combinations.

    **The inverse arm, and why it is the only one that works.** A forward rule
    -- "is this character a possible image" -- is useless here: the images are
    ordinary CJK ideographs, which is what a Chinese file is *supposed* to
    contain, and 52.9% of cp936's whole repertoire is a three-byte image. So
    the rule is the same shape as the two-byte one: the file must contain the
    image **and** a character this image could have come from. Over this tree's
    in-scope files carrying an ideograph, the pair fires **zero** times.

    **The `13` quoted in `pred_lossless_gbk` is not thirteen hits, and never
    was.** It is the number of ideograph-bearing files the *volume arm* rules
    out before the second arm is consulted: 13 of 16, leaving 3 for "the file
    also spells the character" to decide, and **both** predicates report 0 hits
    over the same 16 files. Two instruments, one corpus, no disagreement. The
    previous wording of this sentence -- "against 13 for the two-byte rule on
    the same files" -- reads as thirteen hits, and a careful previous reading
    of this file took it at its word and reported a gate defect that was not
    there. That is the whole measure of what a wrong denominator costs: it
    does not merely mis-state a number, it invites a reader to go looking for
    thirteen missing defects and report them.

    **The four-byte half is unexercised on this tree, and the amount is not
    small.** The 1,024 and 320 byte pairs above resolve to 960 and 256 image
    characters -- 960 + 256 = 1,216, the size of `GBK_MULTIBYTE`, and the two
    figures had better agree. Every source of a four-byte image is
    supplementary-plane, `U+10000`-`U+10FFFF`, 1,048,576 characters, and over
    every source tree in this repository with build output pruned, **0 of 318
    files carry a single one**. So this half is not "0 by luck" and not "0 on a
    small sample": no file here holds a character it could have come from, and
    the count stays 0 whatever else changes. It is kept anyway, because it is
    a fact about the codec rather than about this tree -- the first source file
    carrying an emoji has a member, and a rule deleted while it is quiet is a
    rule that has to be re-derived from a bug report.

    **The message deliberately does not say this half is unexercised.** A
    message prints when the predicate fires, and a predicate that fires is not
    unexercised; a refusal that opens by denying its own applicability is a
    worse read than one that states what it found. What keeps the half from
    being merely believed is `multibyte_gbk_4byte.py`, built by
    `damaged_encoding_fixture.py` and asked for by name in the self-test below
    -- so the honest answer to "is it exercised" is a fixture the gate refuses
    on every run, not a sentence in a docstring.

    **What it cannot catch, and the honest limit of the class:**

    * *A file that is only mojibake.* The damage consumes its own source, so
      if the clean character is nowhere else in the file there is nothing to
      pair the image with. Measured: a string damaged by a real round trip
      scores 0, and the same mojibake pasted beside correct text scores 1.
      The class is reachable and not universal, and this is which one.
    * *The neighbour.* Only the first image is keyed. The second character of
      each damaged pair belongs to the *next* character in the original, so it
      is evidence about a different character and is not evidence here.
    * *Which character should be there.* As with the two-byte rule, the report
      names a character as wrong and never asserts the repair.
    """
    text = _text(data)
    if text is None:
        return None
    if _adjacent_gbk_images(text, GBK_MULTIBYTE):
        return None
    present = set(text)
    hits = []
    for image in sorted(present & set(GBK_MULTIBYTE)):
        shared = sorted(_multibyte_sources(GBK_MULTIBYTE[image]) & present)
        if shared:
            hits.append((text.index(image), image, shared))
    if not hits:
        return None
    off, image, shared = hits[0]
    others = "" if len(hits) == 1 else (
        f" {len(hits) - 1} more character(s) with the same shape are named "
        f"in the full report for this file")
    return (f"carries {len(hits)} cp936 image(s) of a three- or four-byte "
            f"character this file also spells, first at line "
            f"{text.count(chr(10), 0, off) + 1} offset {off}: "
            f"U+{ord(image):04X} is what cp936 reads the first two bytes of "
            f"U+{ord(shared[0]):04X} as, and this file writes both. A UTF-8 "
            f"sequence longer than two bytes cannot survive a cp936 read -- the "
            f"codec takes two bytes per character -- so the character after it "
            f"is read as part of the same pair and this damage walks its "
            f"neighbour. Nothing about the file is malformed: it decodes as "
            f"UTF-8, no byte was lost, and no `?` or U+FFFD was written, which "
            f"is why `pred_lost_byte` and `pred_mojibake_angstrom` are both "
            f"blind to it.{others} Note what makes this a finding rather than a "
            f"coincidence: the clean character has to be somewhere else in this "
            f"same file, because the damage consumed the copy that was here. A "
            f"file that is *only* mojibake will not be caught by this, and that "
            f"is a real limit rather than a caveat."
            + _not_damage())


