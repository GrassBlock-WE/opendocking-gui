def non_ascii_types(root: Path) -> dict[str, int]:
    """Extensions holding non-ASCII bytes outside `SKIP_DIRS`, with counts.

    This is the census that decides the scope, and it deliberately looks at files
    the scan does *not* cover -- otherwise a type nobody thought about would be
    invisible to the rule that exists to notice it. Binaries are skipped: their
    high bytes are not text.
    """
    out: dict[str, int] = {}
    for path in iter_files(root):
        try:
            data = path.read_bytes()
        except OSError:
            continue
        if looks_binary(data) or not any(b > 0x7F for b in data):
            continue
        label = label_of(path)
        out[label] = out.get(label, 0) + 1
    return out


#: How much of a skipped directory this gate will read in order to say what the
#: skip costs. 64 MiB: comfortably above every hand-written tree in this
#: repository and far below `target/`, which is cargo's output and measured
#: unpruned at 4.84 GiB over 11,397 files early on 2026-10-03 and 12,705 files
#: by the end of the same session. **Those figures are quoted as dated
#: measurements and not as properties of the tree**, because they are not: the
#: directory grew by 1,308 files while this line was being edited, and an
#: earlier reading of the same day said 8.37 GB over 15,424. Nothing depends on
#: them. The budget is compared against a *measured* cost every run and the
#: reachability of the directory is proved by
#: `check_skips_cannot_reach_a_release`, which reads the rule rather than a
#: byte count -- so a `target/` that grows to 40 GB changes this line's
#: arithmetic and none of its verdicts.
SKIP_COST_BUDGET = 64 << 20

#: The same idea for the *walk* rather than the read, so a pathologically large
#: directory cannot turn a printed note into an unbounded crawl. 50,000 entries
#: is well above `target/` and well below anything a source tree has.
SKIP_COST_CAP = 50_000


def measure_skip(where: Path) -> dict[str, int | str | bool]:
    """What skipping `where` costs, as numbers a budget can be compared to.

    **Why this is a function returning numbers and not the line that used to
    be printed.** `skip_cost` measured the cost and handed a reader a sentence.
    That is a true positive about the gap and a verdict with no consequence
    attached to it: on 2026-10-02 it printed `1 of them tripping a predicate
    this run did not apply` for a directory holding a genuinely damaged
    hand-written file, and the run still exited 0. Measuring without a
    threshold is a fact nobody is obliged to act on, and a fact nobody acts on
    is the defect this whole addition exists to close. So the measurement is
    separated from the sentence, and the threshold is declared per directory
    in `SKIP_BUDGETS` and compared by `over_budget`.

    Four states come back, and **all four are answers rather than one answer
    with a footnote**, which is what the previous version collapsed them into:

    * `present=False` -- the directory is not in this tree, so this run makes
      no claim about it. Not a pass: a pass would assert something about
      bytes nobody read.
    * `unmeasured=True` -- the directory is larger than `SKIP_COST_BUDGET`,
      which is a read budget about *this measurement* and has nothing to do
      with a damage budget. The count would be a guess, so it is not made.
    * otherwise the numbers are real: `files`, `text_files` and `hits`, where
      `hits` is how many of them this gate's own predicates would refuse.
    """
    out: dict[str, int | str | bool] = {
        "present": False, "unmeasured": False, "truncated": False,
        "files": 0, "text_files": 0, "hits": 0, "bytes": 0, "note": "",
    }
    if not where.is_dir():
        out["note"] = "not present in this tree, so this run makes no claim"
        return out
    out["present"] = True
    total = 0
    found: list[Path] = []
    for p in iter_files(where):
        try:
            total += p.stat().st_size
        except OSError:
            continue
        found.append(p)
        if total > SKIP_COST_BUDGET or len(found) >= SKIP_COST_CAP:
            out["unmeasured"] = True
            break
    out["files"] = len(found)
    out["bytes"] = total
    out["truncated"] = len(found) >= SKIP_COST_CAP and not out["unmeasured"]
    if out["unmeasured"]:
        out["note"] = (f"{total} B over {len(found)} file(s), NOT read: over "
                       f"the {SKIP_COST_BUDGET >> 20} MiB budget for costing a "
                       f"skip. No claim either way about what is in there")
        return out
    text = 0
    hits = 0
    for p in found:
        try:
            data = p.read_bytes()
        except OSError:
            continue
        if b"\x00" in data[:8192]:
            continue
        text += 1
        if verdicts(data):
            hits += 1
    out["text_files"] = text
    out["hits"] = hits
    return out


def over_budget(cost: int, budget: int) -> bool:
    """Is this measured cost over this declared budget?

    **One function, called from two places, and that is the witness for a
    budget.** A budget is an arithmetic claim -- "this skip is allowed to hide
    at most N predicate hits" -- and an arithmetic claim is only falsifiable if
    both sides of the comparison are produced at the same time. The left-hand
    side is a property of a real directory that moves with every build and
    that the gate must not require to exist, so the live comparison alone
    leaves the *operator* untested: `>` quietly becoming `>=` would still be
    green on a tree whose cost is far below every budget. So the self-test
    builds a directory holding a known number of tripping files, measures it
    with `measure_skip`, and asks this same function whether the cost is over
    at the budget and not over one below it.

    **Why this is not the witness-file mechanism, which stays exactly as it
    was.** A witness file answers *does the reason still exist* -- an
    existence question, and the file is the right shape for it because a
    deleted file is a fact about the filesystem that a run can observe. A
    budget answers *does the comparison still hold*, which is not an existence
    question at all: the number in the table never disappears, and deleting
    the directory it was about changes nothing, so a witness file for a budget
    would be a file whose presence says nothing about the arithmetic. What can
    rot is the comparison and the measuring function, so the witness has to
    exercise both -- which is what the fixture does and what a file cannot do.
    The two mechanisms are complementary rather than competing: a skip can
    carry a witness, a budget, or both, and `check_skip_budgets` requires at
    least one.
    """
    return cost > budget


def skip_cost(where: Path) -> str:
    """What skipping `where` costs, in one line, measured rather than declared.

    **Why a skip has to be measured instead of justified.** The skip list used
    to be printed as ten bare names under the heading "build or dependency
    output", and one of the ten -- `opendocking-gui` -- is neither. It is a
    nested *project*: 149 files, 5.1 MB, with its own full `scripts/` tree.
    Measured on 2026-10-02, that directory was hiding three predicate hits, and
    all three are worth a reader's attention even though only two are in
    hand-written source:

    * `scripts/cli_check.py` -- a `pred_lossless_gbk` hit on a *deliberate
      oracle*, a line asserting a decode did **not** produce its cp936 image.
      This is the quotation shape `_not_damage` is about, in a second copy of a
      file whose root-level twin had already been escaped by the same author.
    * `scripts/check_doc_encoding.py` -- a `pred_replacement` hit, and the
      signature is `REPLACEMENT = "\\ufffd"`: an encoding gate holding the very
      character it hunts, as a literal. The self-reference trap this file's own
      module docstring records, sitting in the one file in the tree whose job is
      the same as this one's.
    * `dock-py/python/opendocking/_dockpy.pyd` -- a compiled extension, which
      `EXCLUDED_TYPES` already excludes by name and which is the only one of the
      three that is *not* in scope for any reason other than the directory skip.

    A heading that mislabels a skip is worse than no heading: it tells a reader
    the skip is free of consequence before anyone goes and measures whether it
    is. So the number is here, on every run, with no exemption and nothing to
    maintain.

    **What the number is and is not.** It is what this gate's own predicates
    would find if it looked, which is evidence about the *signatures* in a
    directory and not a verdict on the directory. `dist/` reports a hundred-odd
    hits -- PNGs, `.pyc`, wheels, scratch logs -- and that is the skip working
    exactly as intended, printed so a reader can see the alternative rather than
    take it on trust. Nothing in this line is claimed to be damage.

    The walk stats rather than reads, because "is this small enough to be worth
    counting" is answerable from `st_size` and a count that needed the bytes
    could not be asked of an 8.37 GB build directory at all. Over budget, or over
    the entry cap, the line says so and reports what it did see: an undercount
    costed by an undercount printed as an undercount, which is the only honest
    way to print one.

    **The sentence now also carries the budget, because the sentence is where
    a reader already looks and a number nothing compares against is the printed
    fact nobody acted on.** `measure_skip` does the measuring; this formats it;
    `over_budget` does the comparing; and `check_skip_budgets` is what turns a
    comparison that fails into a red. The four states are printed as four
    different lines, because "absent", "too big to read", "within budget" and
    "over budget" are four different answers and collapsing them into one
    sentence is what let a damaged file inside a skipped directory report as a
    clean run.
    """
    cost = measure_skip(where)
    if not cost["present"]:
        return str(cost["note"])
    if cost["unmeasured"]:
        return str(cost["note"])
    tail = ("" if not cost["truncated"] else
            f"  (undercounted: stopped at the {SKIP_COST_CAP}-entry cap)")
    return (f"{cost['text_files']} text file(s) of {cost['files']}, "
            f"{cost['hits']} of them tripping a predicate this run did not "
            f"apply{tail}")


def print_scope(root: Path, files: list[Path], held: dict[str, int]) -> None:
    """The rule, in the output. A gate whose scope is invisible is the same
    failure as an unpinned total: `0 damaged` has to be a statement about a set
    the reader can name."""
    print("SCOPE -- what this run watched, and what it did not.")
    print()
    print("  Covered suffixes (every matching file was read and judged):")
    for label in sorted(COVERED_TYPES):
        n = sum(1 for f in files if label_of(f) == label)
        held_n = held.get(label, 0)
        print(f"    {label:9s} {n:4d} file(s) scanned, {held_n:4d} holding "
              f"non-ASCII")
    n_nosuffix = sum(1 for f in files if label_of(f) == NO_SUFFIX)
    print(f"    {NO_SUFFIX:9s} {n_nosuffix:4d} file(s) scanned, "
          f"{held.get(NO_SUFFIX, 0):4d} holding non-ASCII"
          f"   -- LICENSE, dotfiles and the `$null` accident, decided by the")
    print(f"    {'':9s} {'':4s} {'':26s}    bytes rather than by a name")
    print()
    print("  Not covered, each with the reason it is not:")
    for label in sorted(EXCLUDED_TYPES):
        print(f"    {label:9s} {EXCLUDED_TYPES[label]}")
    print()
    print("  Not scanned, each with what the skip costs, and the budget that")
    print("  cost is compared against. The cost is measured, the budget is")
    print("  declared, and a cost over its budget is a red in the tally. The")
    print("  third line under each is a DIFFERENT question and is labelled as")
    print("  one: could any of this reach a release? The two axes are never")
    print("  merged, because `target` is the case where they disagree -- its")
    print("  cost is not measured and its unreachability is proved:")
    for name in sorted(SKIP_DIRS):
        budget = SKIP_BUDGETS.get(name, 0)
        cost = measure_skip(root / name)
        if not cost["present"]:
            verdict_line = ("absent -- no claim either way; budget "
                            f"{budget if budget is not None else 'n/a'}")
        elif cost["unmeasured"]:
            verdict_line = ("COST NOT MEASURED -- too large to read, so this "
                            "budget is declared and NOT compared this run")
        elif budget is None:
            verdict_line = ("COST NOT MEASURED -- this directory declares no "
                            "numeric budget")
        else:
            hits = int(cost["hits"])
            if over_budget(hits, budget):
                verdict_line = (f"OVER BUDGET -- cost {hits} against budget "
                                f"{budget}")
            else:
                verdict_line = (f"within budget -- cost {hits} of {budget}, "
                                f"headroom {budget - hits}")
        print(f"    {name:18s} {skip_cost(root / name)}")
        print(f"    {'':18s} {verdict_line}")
        _state, phrase = reachability_tag(name)
        print(f"    {'':18s} REACHABILITY {phrase}")
    print()
    print("  Not watched, stated rather than implied: this gate watches")
    print("  *encodings*. It cannot see a character replaced by a different valid")
    print("  character, and it watches nothing outside the root it was given.")
    print("  A skipped directory is a decision, not a verdict: nothing above says")
    print("  the tree is clean there, only that this run did not look. `docs/` is")
    print("  NOT among the skipped names, and that is deliberate -- see")
    print("  `SKIP_DIRS` for what dropping a document scan would cost.")


def measure(root: Path) -> tuple[list[Path], list[tuple[Path, str]]]:
    """Checks 1-8: the question asked of the tree, or eight counted skips."""
    files, unreadable = walk(root)
    held = non_ascii_types(root)

    section("the scope")
    print_scope(root, files, held)
    print()

    if not files:
        why = (f"nothing under {root} matched the covered types, so there was "
               f"nothing to judge. That is a third answer, distinct from 'clean' "
               f"and from 'damaged': a scope that silently matched nothing is the "
               f"failure this whole scope decision exists to prevent, so it is "
               f"reported and counted rather than passing as 0 damaged")
        skip("the scan scope was resolved, and there was something in it", why)
        for label, _pred, _short in PREDICATES:
            skip(label, why)
        return files, unreadable

    ok("the scan scope was resolved, and there was something in it",
       f"{len(files)} file(s) under {root} match {len(COVERED_TYPES)} covered "
       f"suffix(es) plus the extensionless text rule, and {len(held)} extension(s) "
       f"of them hold non-ASCII bytes. The suffixes covered and the suffixes "
       f"deliberately not are both printed above, so this '0 damaged' is a "
       f"statement about a set the reader can name")

    section("every file, and every predicate's verdict on it")
    hits: dict[str, list[tuple[str, str]]] = {p.__name__: []
                                               for _l, p, _s in PREDICATES}
    for rel in files:
        data = (root / rel).read_bytes()
        found = verdicts(data)
        if found:
            for pred_name in found:
                hits[pred_name].append((rel.as_posix(), found[pred_name]))
        mark = "  ".join(f"{k} x{v}" for k, v in sorted(found.items())) or "clean"
        has_nonascii = any(b > 0x7F for b in data)
        print(f"  {rel.as_posix():56s} {len(data):8d} B  "
              f"{'non-ASCII' if has_nonascii else 'ASCII    '}  {mark}")

    if unreadable:
        print()
        for rel, why in unreadable:
            print(f"  {rel.as_posix():56s} {'unreadable':8s}  {why}")

    for label, pred, _short in PREDICATES:
        found = hits[pred.__name__]
        if unreadable:
            skip(label,
                 f"{len(unreadable)} in-scope file(s) could not be read "
                 f"({', '.join(r.as_posix() for r, _w in unreadable[:4])}"
                 f"{' ...' if len(unreadable) > 4 else ''}), and this predicate "
                 f"cannot judge a file it cannot open. An unreadable file is an "
                 f"OSError rather than a byte pattern, and calling it damage "
                 f"would send a reader to the wrong place")
        elif found:
            bad(label, "; ".join(f"{name} -- {why}" for name, why in found[:6])
                + (" ..." if len(found) > 6 else "")
                + f". {len(found)} file(s) in total. Re-write the file through "
                  f"the write/edit tools or Python; a PowerShell 5.1 round trip "
                  f"is what produced this")
        else:
            ok(label, f"none of the {len(files)} in-scope file(s) trips "
                      f"`{pred.__name__}`")
    return files, unreadable


