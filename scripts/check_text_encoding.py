def main() -> int:
    print("Is any file in this tree carrying the bytes PowerShell 5.1 destroys?")
    root = Path(os.environ.get("OD_ENCODING_SCAN_ROOT", str(ROOT))).resolve()
    if root != ROOT:
        print(f"   (OD_ENCODING_SCAN_ROOT: scanning {root} instead of the tree)")
    section("the measurement")
    files, _unreadable = measure(root)

    section("the scope decision, asked as a question about the tree")
    check_scope_is_answered(root)
    check_exemptions_are_real(root)
    check_skip_budgets(root)
    check_skips_cannot_reach_a_release(root)

    section("the root, asked as a question about what is load-bearing")
    check_root_debris(root)

    section("the arithmetic the tally above prints in words")
    check_ordinal_table()

    section("the self-test: can this gate tell a damaged file from a clean one?")
    where, manifest, problem = build_fixtures()
    # Asked *before* the self-test runs, and about the scan that already ran,
    # so a run whose fixtures are in scope fails on the fact rather than
    # producing a page of red that all point at the same mistake.
    self_reference = fixtures_are_outside_the_scan(root, where, files)
    if self_reference:
        bad("this run's own fixtures are outside the scan it just performed",
            self_reference)
    elif where is None:
        skip("this run's own fixtures are outside the scan it just performed",
             "the fixtures were not built, so there is no directory to place")
    else:
        ok("this run's own fixtures are outside the scan it just performed",
           f"the fixtures were built in {where.resolve()} and the scan walked "
           f"{root.resolve()}. The fixture directory is not inside the scan "
           f"root, so walking the root cannot descend into it, and none of the "
           f"{len(files)} file(s) this run actually scanned lies inside it. "
           f"This is measured against the scan that ran rather than asserted "
           f"about where %TEMP% happens to point: a machine with TEMP inside "
           f"the checkout, or a --out aimed somewhere convenient, would put "
           f"deliberately-damaged files in scope and this run would red on its "
           f"own test data. The fix for that is to move the fixtures, never to "
           f"exclude the directory -- an exclusion is a hand-maintained hole "
           f"that the first different temp layout walks through")
    self_test(where, manifest, problem)
    if where is not None:
        # The fixture is a temp directory and the run is over. Removed through
        # shutil rather than deleted by hand, so the path is not left for a
        # reader to trip over, and so a crash mid-run cannot take the tree with
        # it: nothing outside the temp dir is ever written.
        shutil.rmtree(where, ignore_errors=True)

    tally()
    return finish()


def tally() -> None:
    section("the tally")
    np_ = sum(1 for t, _n, _d in RESULTS if t == "PASS")
    nf = sum(1 for t, _n, _d in RESULTS if t == "FAIL")
    ns = sum(1 for t, _n, _d in RESULTS if t == "SKIP")
    name = "the tally accounts for every result, skips included"
    if np_ + nf + ns == len(RESULTS) == EXPECTED_CHECKS - 1:
        ok(name, f"{np_} + {nf} + {ns} = {len(RESULTS)}, and this check is the "
                 f"{ordinal(len(RESULTS) + 1)}, so the run reaches the declared "
                 f"{EXPECTED_CHECKS} -- the same on this tree, under "
                 f"OD_ENCODING_SCAN_ROOT, and on a machine with no extension, "
                 f"because a skip is a result and a failure does not move the "
                 f"total")
    else:
        bad(name, f"recorded {len(RESULTS)} results ({np_}+{nf}+{ns}) before "
                  f"this check, which must be {EXPECTED_CHECKS - 1}")


def finish() -> int:
    np_ = sum(1 for t, _n, _d in RESULTS if t == "PASS")
    nf = sum(1 for t, _n, _d in RESULTS if t == "FAIL")
    ns = sum(1 for t, _n, _d in RESULTS if t == "SKIP")
    print()
    print(f"--- {np_} passed, {nf} failed, {ns} skipped, {len(RESULTS)} checks "
          f"(expected {EXPECTED_CHECKS})")
    print("    three numbers that never sum to a verdict: a pass count alone "
          "cannot say whether there was anything to scan")
    if nf:
        print(f"RESULT: FAIL -- {nf} of {EXPECTED_CHECKS} checks failed")
        return 1
    print(f"RESULT: OK -- {np_} passed, {ns} could not be measured here")
    return 0


def report_crash(exc: BaseException) -> int:
    """A run that did not finish says so, in the same words as a run that did.

    A file that crashed once after printing a PASS line and a plausible FAIL
    line leaves a reader unable to tell a finished run from a stopped one
    without reading the exit code. The summary is unreachable unless every check
    ran, and an unhandled failure prints `DID NOT FINISH`, which no finished run
    can print.
    """
    import traceback

    traceback.print_exc()
    np_ = sum(1 for t, _n, _d in RESULTS if t == "PASS")
    nf = sum(1 for t, _n, _d in RESULTS if t == "FAIL")
    ns = sum(1 for t, _n, _d in RESULTS if t == "SKIP")
    print()
    print(f"--- STOPPED EARLY after {len(RESULTS)} recorded result(s): "
          f"{np_} passed, {nf} failed, {ns} skipped")
    print(f"RESULT: DID NOT FINISH -- {type(exc).__name__}: {exc}")
    print("    a finished run prints OK or FAIL above and never this line; "
          f"{len(RESULTS)} of {EXPECTED_CHECKS} checks ran")
    return 2


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    try:
        raise SystemExit(main())
    except SystemExit:
        raise
    except BaseException as _exc:  # noqa: BLE001 - the point is to report it
        raise SystemExit(report_crash(_exc))
