def parse_manifest(text: str) -> dict[str, str]:
    """The `damage.<name>=<tag>` lines, and nothing else.

    Prefixed lines only, so prose can be added above without breaking a consumer,
    and a fixture that declares nothing stays declaring nothing rather than
    defaulting -- a default here would let a missing declaration look like a
    correct one.
    """
    out: dict[str, str] = {}
    for line in text.splitlines():
        if line.startswith("damage."):
            key, _, value = line.partition("=")
            out[key.strip()] = value.strip()
    return out


#: The directory name `build_fixtures` creates, in one place. The provenance
#: check keys on it so that the prefix the builder uses and the prefix the check
#: looks for cannot drift into naming different things -- a check that hard-codes
#: a second copy of a string is a check that silently stops matching.
FIXTURE_DIR_PREFIX = "od-damaged-encoding-"

#: The budget witness's directory name, its tripping count and its clean count.
#: **Declared here as the gate's expectation and measured against the
#: directory the builder actually wrote**, rather than read out of the
#: manifest. The two directions matter: reading the counts out of the manifest
#: would make the check compare the builder against itself and always agree,
#: and typing them here means a builder that changed shape goes red instead of
#: quietly testing a cost nobody intended.
FIXTURE_SKIP_DIR = "od-skip-cost-fixture"
FIXTURE_SKIP_HITS = 3
FIXTURE_SKIP_CLEAN = 2

#: Manifest keys that name a *control* rather than a file, so the per-file
#: existence and predicate-short-name tests do not apply to them. Each is
#: verified by the check that owns it instead; see the comment at its use.
MANIFEST_CONTROL_KEYS = ("clean", "accented", "exempt", "skip_fixture")


def build_fixtures() -> tuple[Path | None, dict[str, str], str | None]:
    """`(dir, manifest, problem)`. `problem` is a reason, never a success."""
    out = Path(tempfile.mkdtemp(prefix=FIXTURE_DIR_PREFIX))
    proc = run_script("damaged_encoding_fixture.py", "--out", str(out))
    if proc.returncode != 0:
        return None, {}, (f"{FIXTURE_BUILDER_NAME} exited {proc.returncode}: "
                          f"{(proc.stderr or proc.stdout).strip()[-400:]}")
    try:
        manifest = parse_manifest((out / "DAMAGE.txt").read_text(encoding="utf-8"))
    except OSError as exc:
        return None, {}, f"{out / 'DAMAGE.txt'} is unreadable: {exc}"
    return out, manifest, None


def fixtures_are_outside_the_scan(root: Path, where: Path | None,
                                  files) -> str | None:
    """Why this run's own fixtures cannot be judged by this run's own scan.

    Returns a problem string, or `None` when the fixtures are provably outside
    the scan. **This is a check rather than a comment because a comment is a
    claim about a machine and a check is a claim about this run.**

    The failure it exists to catch is the gate reporting its own fixtures as
    defects. That is not hypothetical in the way it sounds: the fixtures are
    written to `%TEMP%` and the scan walks the repository, so the two are
    disjoint today -- but nothing *tested* that, and the disjointness rests on
    where the OS happens to put `%TEMP%`. A machine with `TEMP` set inside the
    checkout, a CI runner with a different layout, or a future change that
    points `--out` somewhere convenient would put deliberately-damaged files
    inside the scope, and every run would then red on the very fixtures that
    exist to prove the predicates work. The tempting fix is an exclusion for
    the temp directory, and that is exactly the hand-maintained hole this gate
    argues against elsewhere: it would defeat the first run with a different
    temp layout, silently.

    **Two clauses, and the first version of the second could not fire.** Both
    were written to be measured rather than asserted, and measuring them is
    what showed the problem:

    * *containment* -- this run's fixture directory is not inside the scan
      root, so walking the root cannot descend into it at all;
    * *reachability* -- no file in the set this run actually scanned looks
      like a fixture.

    The reachability clause was originally "no scanned file lies inside *this
    run's* fixture directory", and **that is unreachable**: the scan runs
    before `build_fixtures()` creates the directory, so the list is always
    empty and the clause was decoration wearing a measurement's clothes. Two
    trapped runs drove the whole check red on the containment clause with the
    reachability count sitting at `0`, which is the only reason it was noticed.

    What the clause *should* ask is the question that has a failure mode: is
    any scanned file a **fixture**, by path shape? The realistic way the
    fixtures get into scope is not this run's directory -- it is a **stale
    directory left by a run that crashed before its `shutil.rmtree`**, which
    the next run's scan would walk straight into. That is what this asks now,
    and it is keyed on the builder's own prefix rather than on a path anyone
    typed here.
    """
    if where is None:
        return "the fixtures were not built, so there is no directory to place"
    w = where.resolve()
    r = root.resolve()
    under_root = (w == r or r in w.parents)
    # Keyed on the prefix `tempfile.mkdtemp(prefix=...)` is called with below,
    # so the two cannot drift into naming different things.
    # `startswith` on the **directory** components only, and both halves of that
    # were wrong in a first draft that this proof caught.
    #
    # `startswith` rather than exact membership, because `mkdtemp` appends a
    # random suffix: the directory is `od-damaged-encoding-` plus eight more
    # characters, so an exact test against `rel.parts` matched nothing and the
    # clause was unreachable.
    #
    # `parts[:-1]` rather than every part, because a *file* called
    # `od-damaged-encoding-notes.md` is not a fixture directory, and testing
    # the last component flagged it. A comment here claimed the substring case
    # could not match; the run said otherwise, and the run was right. A fixture
    # is always `<somewhere>/od-damaged-encoding-XXXX/<file>`, so the prefix can
    # only ever be a directory in the path.
    stale = [rel.as_posix() for rel in files
             if any(part.startswith(FIXTURE_DIR_PREFIX)
                    for part in rel.parts[:-1])]
    if under_root or stale:
        return (f"the fixture directory is {w} and the scan root is {r}: the "
                f"fixtures are {'INSIDE' if under_root else 'not inside'} the "
                f"root, and {len(stale)} scanned file(s) look like fixtures"
                f"{': ' + ', '.join(stale[:4]) if stale else ''}. "
                f"A gate that judges its own deliberately-damaged fixtures is a "
                f"gate that reports its own test data as defects, and the fix "
                f"is to move the fixtures -- not to exclude the directory, which "
                f"would be a hand-maintained hole that the first run with a "
                f"different temp layout walks straight through")
    return None


def check_accented_prose(where: Path | None, problem: str | None) -> None:
    """Correct accented prose is accepted, including this tree's own notation.

    **This is the check that keeps the cp1252 rule from being wrong in the
    direction that kills it.** A two-character cp1252 image is an accented
    letter followed by one of 59 characters, and this repository writes
    angstrom-cubed 52 times as measured on 2026-10-03 -- the largest single
    body of correct text in the
    tree that is shaped exactly like damaged `U+00F3`. A rule that refused it
    would be a rule whose every run is red on the project's own physics, and
    the response to that is to delete the rule.

    So the negative control is not a formality here; it is the evidence that
    `CP1252_RISKY_SECOND` names the right nine characters rather than an
    arbitrary nine, and the fixture it reads carries a witness for each of
    them plus this tree's own `U+00C5 U+00B3`, `U+00C5 U+00B2`,
    `U+00C5 U+2014` and `U+00D7 U+00B2` shapes.
    """
    name = ("every predicate accepts correct accented prose, including this "
            "tree's own angstrom notation")
    prose = "correct_accented_prose.txt"
    if problem:
        skip(name, problem)
        return
    path = where / prose
    if not path.is_file():
        bad(name, f"{path} was not built, so the cp1252 rule's false-positive "
                  f"rate is unmeasured. A rule about two-character mojibake "
                  f"that has only ever been shown refusing things is a rule "
                  f"whose cost on correct text is a guess")
        return
    data = path.read_bytes()
    found = verdicts(data)
    try:
        text = data.decode("utf-8")
    except UnicodeDecodeError:
        bad(name, f"{prose} does not decode as UTF-8, so it cannot be the "
                  f"correct-text control it claims to be")
        return
    risky_seen = sorted({text[i + 1] for i in range(len(text) - 1)
                         if text[i:i + 2] in CP1252_COMPLETE
                         and text[i:i + 2][1] in CP1252_RISKY_SECOND})
    unwitnessed = [f"U+%04X" % ord(c) for c in CP1252_RISKY_SECOND
                   if c not in risky_seen]
    if found:
        bad(name, f"{prose} ({describe(path)}) is refused by "
                  f"{sorted(found)}: {first_reason(found)}. That file is correct "
                  f"accented text in six languages plus this repository's own "
                  f"physics notation, so a hit here is a false positive about "
                  f"the file, and a false positive about correct text is the "
                  f"one kind this gate cannot recover from")
        return
    if unwitnessed:
        bad(name, f"{prose} carries no occurrence of {', '.join(unwitnessed)}, "
                  f"which CP1252_RISKY_SECOND declares risky. A risky entry "
                  f"with no witness in the control is a claim the fixture does "
                  f"not test, and a claim nobody tests is the second thing to "
                  f"forget")
        return
    ok(name, f"all {len(PREDICATES)} predicates accept {prose} "
              f"({describe(path)}), which holds correct accented text in French, "
              f"Portuguese, Spanish, Czech, Nordic and German, the Chinese "
              f"em-dash convention, CJK, and this tree's own angstrom-cubed, "
              f"angstrom-squared and cross-product-squared notation. The 9 "
              f"characters CP1252_RISKY_SECOND declares risky all appear in it "
              f"after an accented letter, so the exclusion list is witnessed "
              f"rather than asserted, and the 2,891-image set they are drawn "
              f"from produces 0 false positives on {len(text)} characters of "
              f"correct accented text")


def check_budget_arithmetic(where: Path | None, problem: str | None) -> None:
    """The budget comparison fires in both directions on a known cost.

    **Why a live tree cannot be the only evidence.** Every real skip on this
    tree sits far below its budget -- `dist` at 59 of 120, everything else at
    0 -- so a comparison that was simply broken in the permissive direction
    would still be green forever. The witness is therefore a directory the
    fixture builder fills with a *known* number of tripping files, measured by
    the same `measure_skip` the live check uses and compared by the same
    `over_budget`, and it is asked the question three times: at the budget, one
    under it, and one over.

    **And this is where the mechanism differs from a witness file**, which is
    the point worth stating rather than assuming. A witness file answers *does
    the justification still exist*; the file is the right shape for that
    because a deleted file is a fact a run can observe on the filesystem. A
    budget answers *does the comparison still hold*, and no file can witness
    that: the declared number never disappears, and deleting the directory it
    was about changes nothing about whether `cost > budget` is still the test.
    What can rot is the comparison and the measuring function, so the witness
    has to drive both -- which is what this does, and which a file cannot.
    """
    name = ("the skip-budget comparison fires in both directions on a cost of "
            "known size")
    if problem:
        skip(name, problem)
        return
    where_dir = where / FIXTURE_SKIP_DIR
    if not where_dir.is_dir():
        bad(name, f"{where_dir} was not built, so the budget comparison is "
                  f"exercised only against real build directories that sit far "
                  f"below their limits -- which is exactly the state in which a "
                  f"broken comparison looks green")
        return
    cost = measure_skip(where_dir)
    hits = int(cost["hits"])
    files = int(cost["files"])
    want_hits, want_clean = FIXTURE_SKIP_HITS, FIXTURE_SKIP_CLEAN
    problems = []
    if hits != want_hits:
        problems.append(f"the fixture directory holds {want_hits} damaged file(s)"
                        f" by construction and measured {hits}, so either a "
                        f"predicate stopped firing on them or one started")
    if files != want_hits + want_clean:
        problems.append(f"it holds {want_hits + want_clean} file(s) by "
                        f"construction and the walk found {files}")
    if over_budget(hits, hits):
        problems.append(f"`over_budget({hits}, {hits})` is true, so the "
                        f"comparison is off by one and a directory sitting "
                        f"exactly on its budget would go red")
    if not over_budget(hits, hits - 1):
        problems.append(f"`over_budget({hits}, {hits - 1})` is false, so one "
                        f"file over budget would pass")
    if over_budget(0, 0):
        problems.append("`over_budget(0, 0)` is true, so a clean directory "
                        "would go red")
    if problems:
        bad(name, "; ".join(problems))
        return
    ok(name, f"the fixture directory {FIXTURE_SKIP_DIR} was measured at {hits} "
              f"tripping file(s) of {files}, which is what it was built to hold, "
              f"and the same `over_budget` the live check uses answers "
              f"False at {hits}/{hits}, True at {hits}/{hits - 1} and False at "
              f"0/0. So a directory exactly on its budget is green and one file "
              f"over it is red, measured rather than asserted -- which is the "
              f"whole difference between a declared budget and a ratchet with "
              f"no teeth, and it is why a budget's witness is a measured cost "
              f"and not a file: no file can witness an arithmetic claim")


def self_test(where: Path | None, manifest: dict[str, str],
              problem: str | None) -> None:
    """Checks 13-22: this file's own predicates, on files built to be wrong.

    Every check below calls the same function the measurement above called. The
    refusal has to name the file and say which predicate fired, so that a
    fixture which happened to be wrong in some *other* way cannot satisfy it: a
    green here that came from an unrelated refusal would be a green for a reason
    the gate does not understand.
    """
    name = "the self-test fixtures were built and say what they are"
    if problem:
        skip(name, problem)
    else:
        declared = {k[len("damage."):]: v for k, v in manifest.items()
                    if k.startswith("damage.") and ".why." not in k
                    and k not in ("damage.manifest",)}
        # `damage.<name>=<tag> <short predicate name>` -- two machine-readable
        # fields. A declaration that names a predicate this gate does not have is
        # a self-test written against a rule that no longer exists, which would
        # otherwise sit in the fixture looking like coverage.
        shorts = {k: (v.split() + ["", ""])[1] for k, v in declared.items()
                  if k not in MANIFEST_CONTROL_KEYS}
        missing = [k for k in declared
                   if k not in MANIFEST_CONTROL_KEYS and not (where / k).is_file()]
        # A control key is a *label*, not a filename -- `clean` names
        # `clean_baseline.py` and `skip_fixture` names a directory -- so the
        # per-file existence and predicate-name tests do not apply to it. Each
        # one is verified by the check that owns it instead: the clean twin by
        # the negative control below, the accented prose by
        # `check_accented_prose`, and the budget directory by
        # `check_budget_arithmetic`. That is why this is a named list rather
        # than a literal repeated twice: adding a control without adding it
        # here is exactly the kind of omission that shows up as a red about a
        # label rather than about a missing file.
        unknown = sorted({s for s in shorts.values() if s not in BY_SHORT})
        uncovered = sorted(k for k, s in shorts.items() if s not in BY_SHORT)
        if missing:
            bad(name, f"the manifest declares {sorted(missing)} and they are not "
                      f"in {where}. A fixture that was written without being "
                      f"declared, or declared without being written, is the "
                      f"`cp -r` failure mode this manifest exists to prevent")
        elif unknown:
            bad(name, f"the manifest names predicate(s) {unknown} that this gate "
                      f"does not have, and {uncovered} depends on them, so a "
                      f"self-test would be written against rules that no longer "
                      f"exist. The predicates are: {sorted(BY_SHORT)}")
        elif len(BY_SHORT) != len(PREDICATES):
            bad(name, f"two short names resolve to one predicate: "
                      f"{len(BY_SHORT)} names for {len(PREDICATES)} "
                      f"predicates, so two fixtures would prove one thing")
        else:
            ok(name, f"{len(shorts)} mutation(s) declared in "
                     f"{where / 'DAMAGE.txt'}, each naming the predicate it "
                     f"violates and each present on disk; plus a clean twin and a "
                     f"declared-exempt Latin-1 file. Every predicate name is one "
                     f"this gate actually has ({len(BY_SHORT)} of them, one "
                     f"fixture each), so no signature is being checked by a "
                     f"fixture that does not exist, and every one of the "
                     f"{len(shorts)} fixtures is built by {FIXTURE_BUILDER_NAME} "
                     f"rather than by this file -- a gate that wrote its own "
                     f"fixtures would have two places to forget them, and one of "
                     f"them would be the file the self-test is reading")

    mutations = [
        ("the predicate refuses the BOM fixture, naming it",
         "bom_damaged.py", pred_bom),
        ("the predicate refuses the truncated-sequence fixture, naming it",
         "truncated_sequence.py", pred_undecodable),
        ("the predicate refuses the replacement-character fixture, naming it",
         "replacement_char.py", pred_replacement),
        ("the predicate refuses the CJK-lost-byte fixture, naming it",
         "lost_byte_gbk.py", pred_lost_byte),
        ("the predicate refuses the cp1252-dash fixture, naming it",
         "cp1252_dash.py", pred_mojibake_dash),
        ("the predicate refuses the cp1252-Angstrom fixture, naming it",
         "cp1252_angstrom.py", pred_mojibake_angstrom),
        ("the predicate refuses the lossless-cp936 fixture, naming it",
         "lossless_gbk.py", pred_lossless_gbk),
        ("the predicate refuses the multi-byte-cp936 fixture, naming it",
         "multibyte_gbk.py", pred_multibyte_gbk),
        ("the predicate refuses the FOUR-byte cp936 fixture, which is the "
         "half this tree cannot produce on its own",
         "multibyte_gbk_4byte.py", pred_multibyte_gbk),
        ("the predicate refuses the cp1252 accented-letter fixture, which is "
         "the modal mojibake and the one the two older cp1252 rules miss",
         "cp1252_e_acute.py", pred_mojibake_cp1252),
    ]
    for label, fixture, pred in mutations:
        if problem:
            skip(label, problem)
            continue
        path = where / fixture
        if not path.is_file():
            bad(label, f"{path} was not built, so there is nothing for "
                       f"`{pred.__name__}` to refuse")
            continue
        found = verdicts(path.read_bytes())
        if pred.__name__ not in found:
            others = ", ".join(sorted(found)) or "nothing"
            bad(label,
                f"`{pred.__name__}` does not fire on {fixture} ({describe(path)}). "
                f"What did fire: {others}. A predicate that has never been seen "
                f"refuse anything has not been shown to be able to refuse "
                f"anything, and this is the check that would have said so")
            continue
        reason = found[pred.__name__]
        others = sorted(set(found) - {pred.__name__})
        extra = ("" if not others else
                 f" (and {', '.join(others)}, which is what a partially damaged "
                 f"fixture should also trip)")
        ok(label, f"`{pred.__name__}` fires on {fixture} ({describe(path)}) and "
                  f"says why: {reason}{extra}")

    label = "the predicate accepts the clean twin, and accepts no other signature"
    clean = "clean_baseline.py"
    if problem:
        skip(label, problem)
    elif not (where / clean).is_file():
        bad(label, f"{where / clean} was not built, so there is no negative "
                   f"control and a gate whose predicates were all switched off "
                   f"would look identical to this one")
    else:
        found = verdicts((where / clean).read_bytes())
        data = (where / clean).read_bytes()
        if found:
            bad(label, f"the clean twin {clean} ({describe(where / clean)}) is "
                       f"refused by {sorted(found)}: {first_reason(found)}. A "
                       f"predicate that fires on correct non-ASCII teaches its "
                       f"users to ignore it")
        elif not any(b > 0x7F for b in data):
            bad(label, f"the clean twin carries no non-ASCII bytes, so accepting "
                       f"it proves nothing: a gate with every predicate switched "
                       f"off would also accept it. The twin is built with an em "
                       f"dash, an Angstrom sign and a CJK character for that "
                       f"reason")
        else:
            ok(label, f"all {len(PREDICATES)} predicates accept {clean} "
                      f"({describe(where / clean)}), which holds an em dash, an "
                      f"Angstrom sign and a CJK character. Non-ASCII is not "
                      f"damage, and this is the only check in the file that says "
                      f"so")

    check_accented_prose(where, problem)
    check_budget_arithmetic(where, problem)

    label = "the declared Latin-1 fixture is exempt rather than red"
    latin1 = "latin1_fixture.txt"
    if problem:
        skip(label, problem)
    elif not (where / latin1).is_file():
        bad(label, f"{where / latin1} was not built, so the exemption path is "
                   f"untested. A declared exemption nobody exercises is a "
                   f"permanent hole wearing a justification")
    else:
        rel = encode_rel(where / latin1, ROOT)
        ENCODING_EXEMPT[rel] = ("a deliberately Latin-1 test input built by "
                                f"{FIXTURE_BUILDER_NAME} for this run; the escape "
                                f"hatch, exercised so that it is known to open")
        try:
            if not pred_undecodable((where / latin1).read_bytes()):
                bad(label, f"{latin1} is supposed to be Latin-1 and is not: the "
                           f"exemption would be covering a file nothing would "
                           f"have flagged, which is the state check 10 exists to "
                           f"catch")
            elif not ENCODING_EXEMPT:
                bad(label, "the declaration did not take, so the exemption path "
                           "is dead code rather than an open hatch")
            else:
                ok(label, f"{rel} is declared exempt with a reason, and the "
                          f"decode predicate does fire on it "
                          f"({describe(where / latin1)}) -- so the exemption is "
                          f"letting off a file that would otherwise be red, not "
                          f"hiding a file nothing was looking at. Declared for "
                          f"the duration of this run and not persisted, because a "
                          f"Latin-1 fixture that lives in the tree belongs in "
                          f"ENCODING_EXEMPT with a reason a reader can weigh")
        finally:
            ENCODING_EXEMPT.pop(rel, None)


