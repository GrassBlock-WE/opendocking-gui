def _gitignore_names(root: Path) -> set[str]:
    """The path components `.gitignore` names, read out of the file.

    Derived rather than restated, for the reason the rest of this file derives
    everything: a skip list that claims its entries are gitignored while the
    gitignore has moved on is a hole wearing a justification, and the way to
    find out is to read the file rather than to re-assert the claim. Matching is
    on the last path component, because `SKIP_DIRS` prunes by *name* at any
    depth -- `maps` is `examples/maps/` in the gitignore and `maps` here.
    """
    out: set[str] = set()
    try:
        text = (root / ".gitignore").read_text(encoding="utf-8", errors="replace")
    except OSError:
        return out
    for line in text.splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        name = line.strip("/").split("/")[-1]
        if name:
            out.add(name)
    return out


def check_exemptions_are_real(root: Path) -> None:
    """Every declared exemption is still justified by something that exists.

    An exemption that outlives its reason is worse than no exemption: it covers
    a file silently, and the gate reports a clean run over a file it never looked
    at. The self-test below keeps the mechanism exercised, and this keeps its
    entries honest.

    **Two lists, one question, and the second one was previously unasked.**
    `ENCODING_EXEMPT` exempts *files* and `SKIP_DIRS` exempts *directories*, but
    the failure is the same in both: a declaration that no longer describes the
    tree. `SKIP_DIRS` was the worse case of the two, because nothing at all
    asked about it -- its comment asserted that every entry is named in
    `.gitignore`, and on 2026-10-02 seven of ten were and three were not, so the
    assertion had rotted silently. A reader trusting it would have believed
    `opendocking-gui` was build output. It is a nested project, and it is hiding
    two hand-written sources that trip a predicate, which is what
    `print_scope`'s `skip_cost` now prints on every run so the gap is a number
    rather than a comment.

    So a skipped directory is justified by exactly one of two things: a name
    `.gitignore` still carries, or a reason here whose **witness file is
    resolved on every run**. A witness is what stops this table from being the
    second thing to forget -- a skip whose justification has been deleted goes
    red here instead of quietly covering its directory forever. And the reverse
    is checked too, because a reason for a directory nobody skips is a
    justification that has quietly stopped applying to anything.
    """
    stale: list[str] = []
    unjustified: list[str] = []
    for rel, why in sorted(ENCODING_EXEMPT.items()):
        path = Path(rel)
        if not path.is_absolute():
            path = root / rel
        if not path.is_file():
            stale.append(f"{rel} is declared exempt but no longer exists")
            continue
        if not verdicts(path.read_bytes()):
            stale.append(f"{rel} is declared exempt but no predicate fires on it "
                         f"any more, so the exemption covers nothing")

    # The skip half is resolved against **this file's own repository**, never
    # against `root`. `SKIP_DIRS` names directories of the tree this gate lives
    # in, and `OD_ENCODING_SCAN_ROOT` points the *scan* somewhere else without
    # moving the gate or its skip list. The first version of this check read the
    # override root, and pointing the gate at a directory with no `.gitignore`
    # made all ten skips unjustified at once -- a red about the repository, from
    # a run pointed at a different directory, which is precisely the
    # "the same in every environment" property the total exists to keep.
    repo = ROOT
    gitignored = _gitignore_names(repo)
    for name in sorted(SKIP_DIRS):
        if name in gitignored:
            continue
        if name not in SKIP_REASONS:
            unjustified.append(
                f"{name} is skipped but is neither named in .gitignore nor in "
                f"SKIP_REASONS, so nothing states why")
            continue
        _why, witness = SKIP_REASONS[name]
        if witness and not (repo / name / witness).is_file():
            unjustified.append(
                f"{name} is skipped because {witness} exists, and that file is "
                f"not in {repo / name} any more")
    for name in sorted(SKIP_REASONS):
        if name not in SKIP_DIRS:
            unjustified.append(
                f"SKIP_REASONS justifies {name}, which is not in SKIP_DIRS, so "
                f"the justification is applying to nothing")

    named = sorted(n for n in SKIP_DIRS if n in gitignored)
    reasoned = sorted(n for n in SKIP_DIRS if n not in gitignored)
    skip_tail = (
        f"; and all {len(SKIP_DIRS)} skipped directories are justified -- "
        f"{len(named)} named in .gitignore, read out of that file rather than "
        f"asserted here ({', '.join(named)}), and {len(reasoned)} carrying a "
        f"reason in SKIP_REASONS whose witness file was resolved on this run "
        f"({', '.join(reasoned)})")
    if not ENCODING_EXEMPT:
        file_tail = (
            "0 file exemptions: ENCODING_EXEMPT is empty, so every in-scope file "
            "was judged on its own bytes and none was let off. Said out loud "
            "rather than left as an empty dict that reads as coverage -- a "
            "Latin-1 test fixture added to this tree without a declaration here "
            "goes red on the decode check, which is the intended outcome")
    else:
        file_tail = "%d declared: %s" % (
            len(ENCODING_EXEMPT),
            "; ".join(f"{k} -- {v}" for k, v in sorted(ENCODING_EXEMPT.items())))

    if not stale and not unjustified:
        ok("every declared encoding exemption is still justified by something "
           "that exists",
           f"{file_tail}{skip_tail}. Neither list is taken on trust, and a skip "
           f"whose reason has been deleted goes red rather than quietly covering "
           f"its directory -- which is what stops this table from being the "
           f"second thing to forget")
        return
    if stale or unjustified:
        parts = []
        if stale:
            parts.append("file exemptions: " + "; ".join(stale)
                         + ". Delete the entry, or say what it is for")
        if unjustified:
            parts.append(
                "; ".join(unjustified)
                + ". Either the directory is not worth skipping and should be "
                  "scanned, or it is worth skipping and something has to say "
                  "why -- and if that something is a build directory it belongs "
                  "in `.gitignore`, where the next reader and the next tool will "
                  "both see it. An unstated skip is the shape this whole scope "
                  "decision exists to prevent: `0 damaged` has to be a "
                  "statement about a set the reader can name, and a directory "
                  "nobody has justified is not in that set")
        bad("every declared encoding exemption is still justified by something "
            "that exists", " | ".join(parts))
        return
    ok("every declared encoding exemption is still justified by something that "
       "exists", f"{file_tail}{skip_tail}")


def _reach_clause(name: str) -> str:
    """The reachability axis, appended to a cost state as a *separate* clause.

    **Two axes, one line, and the separator is doing the work.** The cost axis
    is `measure_skip`'s four states and answers a question about bytes; this one
    answers a question about the rule. `target/` is the case that makes the
    distinction unavoidable -- its cost is `not measured` and its reachability
    is `proved`, and a reader shown only one of those either believes the damage
    count is known or fails to notice that the skip is justified. So the clause
    is bracketed and labelled rather than merged, and it is derived from the same
    memoised proof the check itself reports (`reachability_proof`), so the tally
    and the check can never quote different numbers.
    """
    _state, phrase = reachability_tag(name)
    return f" [reachability: {phrase}]"


def check_skip_budgets(root: Path) -> None:
    """Every skipped directory's cost is inside a declared budget.

    **The gap this closes, stated as the two runs that found it.** On 2026-10-02
    a genuinely damaged hand-written `.py` was written inside `dist/`, and the
    run printed `1 of them tripping a predicate this run did not apply` and
    exited 0. The measurement was right and the consequence was absent, which
    is worse than not measuring: a printed number that nobody is obliged to act
    on reads as coverage. Deleting the whole directory produced the same green,
    because the cost of an absent directory was also nothing to compare.

    **So the consequence is the arithmetic, and the arithmetic has a declared
    right-hand side.** `SKIP_BUDGETS` says how many predicate hits each skip is
    allowed to hide; `measure_skip` produces the left-hand side; `over_budget`
    compares them; and this check is what turns a failed comparison into a
    non-zero exit. The red names the directory, the cost and the budget, so the
    reader can act on it rather than re-derive it.

    **Three things this deliberately does not do**, because each of them turns
    the rule into the thing it was built to stop:

    * *It does not treat a nonzero cost as a failure.* `dist/` holds 59
      tripping files today and that is build output doing what build output
      does. The budget is what makes the rule survivable: it says 59 is
      expected and the 61st is not.
    * *It does not require every directory to be measurable.* `target/` stops
      costing at the read budget, so its budget is declared `None` and the run
      says `COST NOT MEASURED` rather than passing it. A skip whose cost cannot
      be measured is a *named* state, which is the difference between an
      instrument with a marked blind spot and a gate that is simply silent.
      **What changed in 2026-10-03 is that this state is no longer the whole
      answer for it.** The cost axis above still says `not measured` and still
      means it; the separate reachability axis now says `proved`, because
      `check_skips_cannot_reach_a_release` establishes from the live
      `release_tree_rule.py` that none of the 11,397 real files under it would
      be published. Both clauses are printed on the same state string, bracketed
      and labelled, because the unmeasured cost is a real blind spot and the
      proof is a real answer to a different question.
    * *It does not replace the witness mechanism above.* A skip needs a
      witness, a budget, or both; this check requires one of the two and
      `check_exemptions_are_real` still requires the witness half. Both
      survive, and neither is allowed to stand in for the other.

    **A budget that has never been reached is visible.** Every line prints its
    cost and its headroom, so a reader can tell a budget with room to spare
    from one sitting exactly on its limit, and the self-test proves the
    comparison fires in both directions on a directory whose cost is known
    rather than assumed.
    """
    over: list[str] = []
    undeclared: list[str] = []
    stale_entry: list[str] = []
    repo = ROOT
    gitignored = _gitignore_names(repo)
    states: list[str] = []
    for name in sorted(SKIP_DIRS):
        if name not in SKIP_BUDGETS:
            undeclared.append(f"{name} is skipped and has no entry in "
                              f"SKIP_BUDGETS, so its cost is measured on every "
                              f"run and compared against nothing")
            continue
        budget = SKIP_BUDGETS[name]
        cost = measure_skip(repo / name)
        has_witness = name in gitignored or (
            name in SKIP_REASONS and SKIP_REASONS[name][1] is not None)
        if budget is None and not has_witness:
            undeclared.append(
                f"{name} declares neither a numeric budget nor a witness, so "
                f"this run has no way to say anything about what it is hiding")
            continue
        if not cost["present"]:
            states.append(f"{name} absent (budget {budget})"
                          + _reach_clause(name))
            continue
        if cost["unmeasured"] or budget is None:
            states.append(f"{name} cost not measured (budget "
                          f"{'none declared' if budget is None else budget})"
                          + _reach_clause(name))
            continue
        hits = int(cost["hits"])
        if over_budget(hits, budget):
            over.append(f"{name} is hiding {hits} predicate hit(s) against a "
                        f"declared budget of {budget}"
                        + ("" if has_witness else
                           ", and carries no witness either"))
        else:
            states.append(f"{name} {hits}/{budget}" + _reach_clause(name))
    for name in sorted(SKIP_BUDGETS):
        if name not in SKIP_DIRS:
            stale_entry.append(f"SKIP_BUDGETS budgets {name}, which is not "
                               f"skipped, so the budget is comparing nothing")
    if over or undeclared or stale_entry:
        parts = []
        if over:
            parts.append(
                "cost over budget: " + "; ".join(over)
                + ". Either something in there is damaged, or the budget is "
                  "stale because the directory changed. Look at the files "
                  "before raising the number: a budget raised to make a red go "
                  "away is the mechanism learning to be quiet, and the whole "
                  "point of declaring one is that it bites")
        if undeclared:
            parts.append("unmeasured skips: " + "; ".join(undeclared))
        if stale_entry:
            parts.append("; ".join(stale_entry))
        bad("every skipped directory's cost is inside a declared budget",
            " | ".join(parts))
        return
    ok("every skipped directory's cost is inside a declared budget",
       f"all {len(SKIP_DIRS)} skipped directories were measured on this run and "
       f"every one that could be measured is within the budget declared for it: "
       f"{', '.join(states)}. A budget is a number somebody typed above a "
       f"measured cost, so it is a ratchet that can go stale, which is why the "
       f"comparison is `cost > budget` through one function that the self-test "
       f"exercises in both directions on a directory of known cost rather than "
       f"trusting a live tree to be far enough below its limits. A directory "
       f"too large to cost -- `target` is the only one -- is printed as NOT "
       f"MECHASURED rather than passed, because a named blind spot is an "
       f"instrument and a silent one is a false green. Each state carries a "
       f"second, separately labelled clause saying whether the directory is one "
       f"the release rule would publish, because `target` is the case where "
       f"those two answers differ and collapsing them would either claim its "
       f"damage count is known or discard the proof that its contents cannot "
       f"reach a release")


