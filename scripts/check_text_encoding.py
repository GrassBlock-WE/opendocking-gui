def check_scope_is_answered(root: Path) -> None:
    """Every extension holding non-ASCII is covered, or carries a stated reason.

    This is the check that would have caught the gap this file was rewritten to
    close. The previous scope was `*.md` plus `LICENSE`, and 40 of the 83
    Python files in this tree hold non-ASCII; nothing asked whether that was
    intended, so the blindness was invisible from the outside -- the gate
    printed a confident count over a set nobody had written down.

    So the question is no longer "is this file clean" but "has a decision been
    made about every type that could be damaged", and the decision has to be
    either in `COVERED_TYPES` or in `EXCLUDED_TYPES`. Adding a `.rs` file with
    Chinese comments therefore cannot be silently ignored.
    """
    held = non_ascii_types(root)
    undecided = sorted(t for t in held
                       if t not in COVERED_TYPES and t not in EXCLUDED_TYPES
                       and t != NO_SUFFIX)
    if undecided:
        bad("every file type holding non-ASCII is covered or has a stated "
            "exclusion",
            f"{len(undecided)} type(s) hold non-ASCII bytes and appear in "
            f"neither COVERED_TYPES nor EXCLUDED_TYPES: "
            + ", ".join(f"{t} ({held[t]} file(s))" for t in undecided)
            + ". There are three answers, not two: add the suffix to "
              "COVERED_TYPES; add it to EXCLUDED_TYPES with a reason; or delete "
              "the file, if it is a shell's scratch output that this repository "
              "should not contain -- a `.out` in the root is that third case and "
              "it is deliberately in neither table (see the module docstring). "
              "An unlisted type is an oversight; a listed one is a judgement, and "
              "this is the check that says so")
        return
    covered = sorted(t for t in held if t in COVERED_TYPES or t == NO_SUFFIX)
    ok("every file type holding non-ASCII is covered or has a stated exclusion",
       f"all {len(held)} type(s) holding non-ASCII bytes are accounted for: "
       f"{len(covered)} covered ({', '.join(covered)}) and "
       f"{len([t for t in held if t in EXCLUDED_TYPES])} carrying a stated "
       f"exclusion. Nothing in this tree is being watched by accident or not at "
       f"all")


