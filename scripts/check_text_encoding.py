def _docstring_consts(tree) -> set[int]:
    """`id()` of every Constant that is a docstring, so prose is not a reference.

    A docstring is a place a file is *described*, not a place it is *named*. The
    two have to be separable, because every hit in this repository's gates is
    prose first: `$null` is described in four places and named once.
    """
    out: set[int] = set()
    for node in ast.walk(tree):
        if isinstance(node, (ast.Module, ast.ClassDef, ast.FunctionDef,
                             ast.AsyncFunctionDef)):
            body = getattr(node, "body", None)
            if body and isinstance(body[0], ast.Expr) and \
                    isinstance(body[0].value, ast.Constant) and \
                    isinstance(body[0].value.value, str):
                out.add(id(body[0].value))
    return out


def _is_root_name(lit: str) -> bool:
    """Is this literal a whole path at the repository root?

    Only a bare name qualifies. Everywhere else in `scripts/` a string literal is
    a *fragment* -- `(SRC / 'opendocking' / 'cli.py')`, `f'{stem}.png'` -- and a
    fragment cannot be resolved without the prefix the code supplies at runtime.
    That asymmetry is why this check exists at the root and nowhere else: at the
    root there is no prefix to supply, so `'odck.md'` IS the path. Measured over
    this tree, a whole-tree walk of every path-shaped literal finds 1,695 and
    resolves 454; restricting to bare root names is the only place the derivation
    is a measurement rather than a guess.
    """
    if not lit or len(lit) > 80 or "/" in lit or "\\" in lit or "\n" in lit:
        return False
    if lit.startswith(("-", "+", ".", " ")) or " " in lit:
        return False
    if any(c in lit for c in "*?[]{}<>|"):
        return False
    # a filename: a suffix past the first character, or a shell artifact
    return "." in lit[1:] or lit.startswith("$")


def _root_literals_in_code() -> dict[str, list[str]]:
    """`{root name: ["gate.py:line", ...]}` for code-level literals only.

    Derived by walking the other gates' syntax trees. No name is written here:
    the walk finds them, and a name that stops being written stops being found,
    which is the property that makes this a measurement rather than a list.
    """
    found: dict[str, list[str]] = {}
    for gate in sorted(SCRIPTS.glob("*.py")):
        try:
            tree = ast.parse(gate.read_text(encoding="utf-8", errors="replace"))
        except (SyntaxError, ValueError):
            continue
        prose = _docstring_consts(tree)
        for node in ast.walk(tree):
            if not isinstance(node, ast.Constant) or \
                    not isinstance(node.value, str) or id(node) in prose:
                continue
            if _is_root_name(node.value):
                found.setdefault(node.value, []).append(
                    f"{gate.name}:{node.lineno}")
    return found


def check_root_debris(root: Path) -> None:
    """Every root file is either declared source, or named by a gate, or a
    candidate a reader has to think about.

    The accident this closes: an agent offered to `rm --` two files it did not
    create, and one of them was load-bearing. The gate could not have stopped it,
    because no check asked whether a file that *looks* like debris *is* debris.

    The measurement has two halves and they answer different questions.

      A file a gate NAMES is not debris by definition -- deleting it would make
      a gate's own documented table describe a tree that no longer exists. This
      is not a prediction that a gate goes red; it is that the ledger and the
      tree stop agreeing. `$null` is the worked case: it is named once, as a key
      in `GITIGNORE_ANSWERS`, and the `.gitignore` line it answers is still
      answered correctly after the file is gone, so no check goes red. The
      breakage is silent, which is why it needs a check.

      A file NO gate names, and which is not declared source, is debris by
      elimination -- and this check does not fail on it, because deleting debris
      is the intended outcome of the walk above. Failing here would make every
      future scratch file a red gate, which is a noise source, not a detector.

    So the check is a partition, and both branches are reported.
    """
    name = "every root file is declared source, named by a gate, or plainly " \
           "unclaimed"
    declared = set()
    rule = SCRIPTS / "release_tree_rule.py"
    if rule.is_file():
        try:
            import importlib.util as _ilu
            spec = _ilu.spec_from_file_location("_rte_probe", rule)
            mod = _ilu.module_from_spec(spec)
            spec.loader.exec_module(mod)
            declared = set(mod.ROOT_SOURCE_NAMES)
        except Exception as exc:  # noqa: BLE001 - a probe must not crash a gate
            skip(name, f"release_tree_rule.py did not load ({type(exc).__name__}: "
                       f"{exc}), so 'declared source' cannot be told from "
                       f"'named by a gate'")
            return
    else:
        # Found by `scripts/guarded_sites_check.py`, which classifies guards by
        # what they do to the tally and named this one: the `try` below skips
        # correctly when the file is there and unreadable, and the guard *above*
        # it did not, so an absent rule lost the skip entirely and fell through
        # to classify every root file with `declared = set()` -- which does not
        # report "I could not ask", it reports a verdict about the wrong thing.
        skip(name, f"release_tree_rule.py is not present under {SCRIPTS}, so "
                   f"'declared source' cannot be told from 'named by a gate'")
        return

    # `root` is the directory being asked about, so this check can be pointed
    # at a shadow tree by a test and still measures what it says it measures.
    # The GATES it walks are this repository's own, either way: the question is
    # what the gates name, and a shadow tree has no gates of its own.
    root_files = sorted(p.name for p in root.iterdir() if p.is_file())
    named = _root_literals_in_code()

    load_bearing, unclaimed = [], []
    for f in root_files:
        if f in declared or f in named:
            continue
        unclaimed.append(f)

    load_bearing = sorted(f for f in named if f in root_files)

    if not root_files:
        bad(name, "the root has no files in it at all, which is not a tree")
        return
    if unclaimed and not named:
        ok(name, f"none of the {len(root_files)} root file(s) is named by any "
                 f"gate, and {len(unclaimed)} of them "
                 f"({', '.join(unclaimed[:6])}) are neither declared source nor "
                 f"named anywhere -- unclaimed, and this check does not fail on "
                 f"that, because that is what debris looks like and refusing to "
                 f"fail is the only way the word means something")
        return
    ok(name, f"{len(root_files)} root file(s): {len(declared & set(root_files))} "
             f"declared source, {len(load_bearing)} named by a gate in code "
             f"({', '.join(load_bearing[:6])}"
             f"{' ...' if len(load_bearing) > 6 else ''}), and "
             f"{len(unclaimed)} unclaimed ({', '.join(unclaimed[:6])}"
             f"{' ...' if len(unclaimed) > 6 else ''}). Named is not the same as "
             f"opened: a gate naming a file in a table is a ledger the file has "
             f"to keep, and a file nobody names is debris by elimination")


