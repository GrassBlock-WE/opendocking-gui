# The one piece of arithmetic this gate prints in words
# --------------------------------------------------------------------------


#: `(count, ordinal)` pairs, the table the derived rule below is held to.
#:
#: A table rather than a prose claim because a wrong ordinal is invisible: the
#: sentence still parses, the number in it is still right, and only the word is
#: wrong. The tally's own check prints its own position in the sequence, so a
#: suffix that is hardcoded rather than derived is wrong for every count ending
#: in 2 or 3 -- `22th`, `23rd`, `103rd` -- and this gate's total is 23, so the
#: run was printing a malformed ordinal in the one line whose whole job is to be
#: read. **The trap is the teens, and both bands of it:** a rule written as
#: `n % 10` alone gets 11, 12, 13, 111, 112 and 113 wrong, which is why
#: `ORDINAL_TEENS` below is consulted before the last digit and why this table
#: carries all six rather than one.
ORDINAL_TABLE: tuple[tuple[int, str], ...] = (
    (0, "0th"), (1, "1st"), (2, "2nd"), (3, "3rd"), (4, "4th"),
    (10, "10th"), (11, "11th"), (12, "12th"), (13, "13th"), (14, "14th"),
    (20, "20th"), (21, "21st"), (22, "22nd"), (23, "23rd"), (24, "24th"),
    (100, "100th"), (101, "101st"), (102, "102nd"), (103, "103rd"),
    (111, "111th"), (112, "112th"), (113, "113th"),
    (1000, "1000th"), (1001, "1001st"), (1002, "1002nd"), (1003, "1003rd"),
    (1011, "1011th"), (1012, "1012th"), (1013, "1013th"),
    (1111, "1111th"), (1112, "1112th"), (1113, "1113th"),
)

#: The two digits that take `th` whatever the last digit says. English switches
#: to `th` for the whole of 11-13 and then again for any number ending in 11,
#: 12 or 13, so the rule tests the last *two* digits and not the last one.
ORDINAL_TEENS = (11, 12, 13)


def ordinal(n: int) -> str:
    """`n` in English ordinal form, derived rather than hardcoded.

    The two-step that makes it correct: the last two digits decide `th` first,
    and only then does the last digit get a say. Reversing those two tests is
    the bug this exists to prevent, because it produces output that is wrong
    for six numbers in every hundred and never wrong for any of the other
    ninety-four -- the shape of a rule that survives review by accident.

    Negative counts are not a case worth pretending to handle: nothing in this
    file counts downwards, and a fabricated ordinal for `-1` would be a guess
    dressed as a rule. The table below pins the domain to the non-negative
    integers rather than leaving it open.
    """
    if n % 100 in ORDINAL_TEENS:
        return f"{n}th"
    suffix = {1: "st", 2: "nd", 3: "rd"}.get(n % 10, "th")
    return f"{n}{suffix}"


def check_ordinal_table() -> None:
    """The derived ordinal matches the table, entry by entry.

    Its own check rather than a line in the tally's, for two reasons. It is a
    different question -- is this arithmetic right -- from the question the
    tally asks -- did the run record what it promised -- and folding the second
    into the first would make a green here mean both at once. And it never
    skips: the table is a constant and the arithmetic is pure, so this is the
    one check in the file whose answer cannot depend on what is on disk, and a
    skip here would be a check that declines to measure something it can always
    measure.
    """
    wrong = [(n, ordinal(n), want) for n, want in ORDINAL_TABLE
             if ordinal(n) != want]
    if wrong:
        bad("the ordinal the tally prints is derived and correct at the traps",
            f"{len(wrong)} of {len(ORDINAL_TABLE)} table entries disagree with "
            f"`ordinal`: "
            + "; ".join(f"{n} -> got {got!r}, want {want!r}"
                        for n, got, want in wrong[:8])
            + (f"; and {len(wrong) - 8} more" if len(wrong) > 8 else "")
            + ". The table is the specification, not a sample: it carries both "
              "bands of the teens (11-13 and 111-113) precisely because a rule "
              "written on the last digit alone gets all six wrong, and the run "
              "prints this ordinal in the line stating its own total")
        return
    ok("the ordinal the tally prints is derived and correct at the traps",
       f"all {len(ORDINAL_TABLE)} entries of `ORDINAL_TABLE` match `ordinal`, "
       f"including the six a last-digit rule gets wrong (11, 12, 13, 111, 112, "
       f"113) and the four-digit band above them. The teens are decided on the "
       f"last two digits first, so they win over the units digit in both places "
       f"English switches to `th`")


